import { chromium } from "playwright";
import { writeFileSync, mkdirSync } from "node:fs";
mkdirSync("/tmp/muster", { recursive: true });
const base = "http://localhost:3000";
const b = await chromium.launch({ executablePath: "/opt/pw-browsers/chromium" }).catch(() => chromium.launch());
const ctx = await b.newContext(); const p = await ctx.newPage();
await p.goto(base + "/login");
await p.fill("input[name=email]", "admin@foxandpeople.at");
await p.fill("input[name=passwort]", process.env.SEED_PASSWORD ?? "FoxPeople2026!");
await p.click("form button");
await p.waitForURL((u) => !u.pathname.startsWith("/login"));
const hol = async (url, datei) => { const r = await p.request.get(base + url); if (!r.ok()) { console.log("FEHLT", url, r.status()); return; } writeFileSync("/tmp/muster/" + datei, await r.body()); console.log("ok", datei, (await r.body()).length); };
await hol("/agb/ueberlassung", "AGB_Arbeitskraefteueberlassung_2026-08.pdf");
await hol("/agb/vermittlung", "AGB_Arbeitskraeftevermittlung_2026-08.pdf");
// Stundennachweis + Monatsbericht des Test-Mitarbeiters
await p.goto(base + "/stundennachweise?status=BESTAETIGT");
const link = await p.locator("a[href$='/pdf']").first().getAttribute("href");
if (link) await hol(link, "Muster_Stundennachweis_Woche.pdf");
const person = await p.locator("a[href^='/personen/']").first().getAttribute("href");
if (person) await hol(person + "/monatsbericht?jahr=2026&monat=8", "Muster_Monatsbericht.pdf");
await p.goto(base + "/stundennachweise?status=BESTAETIGT");
await p.screenshot({ path: "/tmp/muster/Screenshot_Arbeitszeitaufzeichnung.png", fullPage: true });
await p.goto(base + "/compliance");
await p.screenshot({ path: "/tmp/muster/Screenshot_Compliance.png", fullPage: true });
await p.goto(base + "/controlling?tab=fehlzeiten");
await p.screenshot({ path: "/tmp/muster/Screenshot_Fehlzeiten.png", fullPage: true });
await p.goto(base + "/controlling?tab=recruiting");
await p.screenshot({ path: "/tmp/muster/Screenshot_Recruiting.png", fullPage: true });
await b.close();
